// Freezes fixed AP-format mock exams into data/mock-exams.json.
// Run after the banks change:  node scripts/build_mock_exams.cjs
// Selection is seeded and balanced round-robin across chapters, and never repeats a problem between
// mocks until a pool runs out, so Mock 1 is always the same Mock 1 until you regenerate on purpose.
const fs = require('fs'), path = require('path');
const core = require('../js/practice-core.js');
const read = f => { try { return JSON.parse(fs.readFileSync(path.join(__dirname, '..', 'data', f), 'utf8')); } catch (e) { return {}; } };

function rng(seed) { let a = seed >>> 0; return () => { a = (a + 0x6D2B79F5) >>> 0; let t = a; t = Math.imul(t ^ (t >>> 15), t | 1); t ^= t + Math.imul(t ^ (t >>> 7), t | 61); return ((t ^ (t >>> 14)) >>> 0) / 4294967296; }; }
function shuffle(a, r) { a = a.slice(); for (let i = a.length - 1; i > 0; i--) { const j = Math.floor(r() * (i + 1)); [a[i], a[j]] = [a[j], a[i]]; } return a; }

// Official format per course. calculator:null = not tagged in our banks, shown as a rule only.
const COURSES = {
  'ap-calculus-bc': {
    name: 'AP Calculus BC', prefix: 'calculus', mocks: 4, publish: 3, seed: 20261103, // 4 are generated so the checkpoints keep avoiding the same problems; only the first 3 are published
    sections: [
      { id: '1A', name: 'Section I, Part A: multiple choice', kind: 'mcq', count: 30, minutes: 60, calculator: false },
      { id: '1B', name: 'Section I, Part B: multiple choice', kind: 'mcq', count: 15, minutes: 45, calculator: true },
      { id: '2A', name: 'Section II, Part A: free response', kind: 'frq', count: 2, minutes: 30, calculator: true },
      { id: '2B', name: 'Section II, Part B: free response', kind: 'frq', count: 4, minutes: 60, calculator: false }
    ],
    // Pools: MCQ from every T chapter plus C chapter 11 (miscellaneous MCQ); FRQ from C chapter 12.
    mcqPool: p => p.kind === 'T' || (p.kind === 'C' && p.chapter === '11'),
    frqPool: p => p.kind === 'C' && p.frq,
    // Cumulative checkpoints: one 80-minute multiple-choice sitting drawn from the T problems of the listed chapters (never a problem a
    // generated mock already uses). About two thirds no-calculator, one third calculator, balanced round-robin across the chapters.
    checkpoints: [
      { id: 'cp1', name: 'Checkpoint 1 · Chapters 1-2', chapters: ['1', '2'], count: 40, minutes: 80 },
      { id: 'cp2', name: 'Checkpoint 2 · Chapters 3-4', chapters: ['3', '4'], count: 40, minutes: 80 },
      { id: 'cp3', name: 'Checkpoint 3 · Chapters 5-8', chapters: ['5', '6', '7', '8'], count: 40, minutes: 80 },
      { id: 'cp4', name: 'Checkpoint 4 · Chapters 9-10', chapters: ['9', '10'], count: 40, minutes: 80 }
    ],
    scoring: { mcqWeight: 0.5, frqWeight: 0.5, frqMaxEach: 9, bands: [[0.62, 5], [0.49, 4], [0.37, 3], [0.26, 2], [0, 1]] },
    notes: ['Real exam: Part A of each section is without a calculator and Part B allows one. These mocks follow that: the no-calculator parts draw only no-calculator problems, the calculator parts only calculator ones.', 'Free-response questions are self-scored from the written solution, 0 to 9 points each.']
  },
  'ap-chemistry': {
    name: 'AP Chemistry', prefix: 'chemistry', mocks: 5, seed: 20261104,
    sections: [
      { id: '1', name: 'Section I: multiple choice', kind: 'mcq', count: 60, minutes: 90, calculator: true },
      { id: '2', name: 'Section II: free response', kind: 'frq', count: 7, minutes: 105, calculator: true }
    ],
    mcqPool: p => p.kind === 'T',
    frqPool: p => p.kind === 'C' && p.frq,
    scoring: { mcqWeight: 0.5, frqWeight: 0.5, frqMaxEach: 7, bands: [[0.62, 5], [0.49, 4], [0.37, 3], [0.26, 2], [0, 1]] },
    notes: ['The free-response bank for Chemistry is not built yet, so these mocks are multiple choice only.']
  }
};

const out = { _readme: 'Generated by scripts/build_mock_exams.cjs. Do not hand-edit; change the script and re-run. Problem ids match js/practice-core.js normalize().' };
Object.keys(COURSES).forEach(id => {
  const c = COURSES[id];
  const probs = [['C', read(c.prefix + '-c-bank.json')], ['T', read(c.prefix + '-t-bank.json')]].flatMap(([k, b]) => core.normalize(b, id, k)).filter(p => !p.blocked && p.stem);
  const mcq = probs.filter(c.mcqPool).filter(p => !p.frq && p.choices.length), frq = probs.filter(c.frqPool);
  const r = rng(c.seed);
  // Calculus problems carry a calculator rule in the source (C/T chapters and C11: Part A no calculator, Part B calculator;
  // C12 is the other way round), so Part A / Part B of a mock draw from the matching pool. Other courses are untagged.
  const calcOf = p => { const m = /^\d+[CT]([AB])/.exec(p.id); if (!m || id !== 'ap-calculus-bc') return 'any'; const b = m[1] === 'B'; return p.chapter === '12' ? (b ? 'no' : 'yes') : (b ? 'yes' : 'no'); };
  const tagged = id === 'ap-calculus-bc';
  const secCalc = s => tagged ? (s.calculator ? 'yes' : 'no') : 'any';
  const pools = { mcq: {}, frq: {} };
  mcq.forEach(p => { const k = calcOf(p), ch = p.chapter; ((pools.mcq[k] = pools.mcq[k] || {})[ch] = pools.mcq[k][ch] || []).push(p.id); });
  Object.keys(pools.mcq).forEach(k => Object.keys(pools.mcq[k]).forEach(ch => pools.mcq[k][ch] = shuffle(pools.mcq[k][ch], r)));
  frq.forEach(p => (pools.frq[calcOf(p)] = pools.frq[calcOf(p)] || []).push(p.id));
  Object.keys(pools.frq).forEach(k => pools.frq[k] = shuffle(pools.frq[k], r));
  const take = (k, n) => { // n problems from the chapters of pool k, round-robin so every chapter shows up
    const byCh = pools.mcq[k] || {}, picked = [];
    while (picked.length < n) {
      const chs = shuffle(Object.keys(byCh).filter(ch => byCh[ch].length), r);
      if (!chs.length) return null;
      for (const ch of chs) { if (picked.length < n && byCh[ch].length) picked.push(byCh[ch].shift()); }
    }
    return picked;
  };
  const mocks = [];
  for (let m = 0; m < c.mocks; m++) {
    const secs = {}; let ok = true;
    for (const s of c.sections) {
      if (s.kind === 'mcq') { const got = take(secCalc(s), s.count); if (!got) { ok = false; break; } secs[s.id] = shuffle(got, r); }
      else if (frq.length) { const q = pools.frq[secCalc(s)] || []; if (q.length < s.count) { ok = false; break; } secs[s.id] = q.splice(0, s.count); }
    }
    if (!ok) break; // not enough problems for another full mock
    mocks.push({ id: 'mock' + (m + 1), name: 'Mock ' + (m + 1), sections: secs });
  }
  // Checkpoints use their own generator so the mocks above never change when a checkpoint is added or edited.
  const checkpoints = [];
  if (c.checkpoints) {
    const used = new Set(); mocks.forEach(m => Object.values(m.sections).forEach(l => l.forEach(x => used.add(x))));
    const taken = new Set(), cr = rng(c.seed + 7);
    c.checkpoints.forEach(cp => {
      const pool = {}; // calc kind -> chapter -> ids
      mcq.filter(p => p.kind === 'T' && cp.chapters.indexOf(p.chapter) >= 0 && !used.has(p.id) && !taken.has(p.id)).forEach(p => { const k = calcOf(p); ((pool[k] = pool[k] || {})[p.chapter] = pool[k][p.chapter] || []).push(p.id); });
      Object.keys(pool).forEach(k => Object.keys(pool[k]).forEach(ch => pool[k][ch] = shuffle(pool[k][ch], cr)));
      const pull = (k, n) => { const by = pool[k] || {}, got = []; while (got.length < n) { const chs = shuffle(Object.keys(by).filter(ch => by[ch].length), cr); if (!chs.length) break; for (const ch of chs) if (got.length < n && by[ch].length) got.push(by[ch].shift()); } return got; };
      const nCalc = Math.round(cp.count / 3), noCalc = pull('no', cp.count - nCalc);
      let calc = pull('yes', nCalc);
      if (noCalc.length + calc.length < cp.count) calc = calc.concat(pull('no', cp.count - noCalc.length - calc.length)); // pool short: fill from the other kind
      const pids = shuffle(noCalc.concat(calc), cr); pids.forEach(x => taken.add(x));
      checkpoints.push({ id: cp.id, name: cp.name, chapters: cp.chapters, minutes: cp.minutes, pids });
      console.log('  ' + cp.id + ': ' + pids.length + ' problems (' + noCalc.length + ' no-calc, ' + calc.length + ' calc)');
    });
  }
  const frqTotal = c.sections.filter(s => s.kind === 'frq').reduce((n, s) => n + s.count, 0);
  out[id] = { name: c.name, sections: c.sections.map(s => Object.assign({}, s, { available: s.kind === 'mcq' || frq.length >= frqTotal })), scoring: c.scoring, notes: c.notes, mocks: c.publish ? mocks.slice(0, c.publish) : mocks, checkpoints };
  console.log(id + ': ' + mocks.length + ' mocks; mcq pool ' + mcq.length + ', frq pool ' + frq.length);
});
fs.writeFileSync(path.join(__dirname, '..', 'data', 'mock-exams.json'), JSON.stringify(out, null, 1) + '\n');
